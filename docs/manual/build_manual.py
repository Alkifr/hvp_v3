fig_no = 0


def set_run_font(run, name="Times New Roman", size=12, bold=False, italic=False, color=None):
    run.font.name = name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    if color:
        run.font.color.rgb = RGBColor(*color)


def shade_cell(cell, hex_color):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:fill"), hex_color)
    shd.set(qn("w:val"), "clear")
    tcPr.append(shd)


def add_page_number(paragraph):
    run = paragraph.add_run()
    set_run_font(run, size=10, color=(80, 80, 80))
    fld_begin = OxmlElement("w:fldChar")
    fld_begin.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = " PAGE "
    fld_end = OxmlElement("w:fldChar")
    fld_end.set(qn("w:fldCharType"), "end")
    run._r.append(fld_begin)
    run._r.append(instr)
    run._r.append(fld_end)


def add_toc(paragraph):
    run = paragraph.add_run()
    r = run._r
    begin = OxmlElement("w:fldChar")
    begin.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = ' TOC \\o "1-2" \\h \\z \\u '
    separate = OxmlElement("w:fldChar")
    separate.set(qn("w:fldCharType"), "separate")
    placeholder = OxmlElement("w:t")
    placeholder.text = "Откройте документ в Word и обновите поле содержания (ссылки и номера страниц подставятся сами)."
    end = OxmlElement("w:fldChar")
    end.set(qn("w:fldCharType"), "end")
    r.append(begin)
    r.append(instr)
    r.append(separate)
    r2 = OxmlElement("w:r")
    r2.append(placeholder)
    paragraph._p.append(r2)
    r3 = paragraph.add_run()._r
    r3.append(end)


def style_body(p, center=False, after=8, before=0, size=12):
    pf = p.paragraph_format
    pf.space_after = Pt(after)
    pf.space_before = Pt(before)
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = 1.15
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if center else WD_ALIGN_PARAGRAPH.JUSTIFY
    for run in p.runs:
        set_run_font(run, size=size)


class Manual:
    def __init__(self):
        self.doc = Document()
        sec = self.doc.sections[0]
        sec.page_width = Cm(21.0)
        sec.page_height = Cm(29.7)
        sec.left_margin = Cm(2.0)
        sec.right_margin = Cm(1.5)
        sec.top_margin = Cm(1.8)
        sec.bottom_margin = Cm(1.8)
        sec.header_distance = Cm(0.6)
        sec.footer_distance = Cm(0.6)

        header = sec.header.paragraphs[0]
        header.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        hr = header.add_run("HVP — Hangar Visit Plan")
        set_run_font(hr, size=10, color=(70, 90, 120))

        footer = sec.footer.paragraphs[0]
        footer.alignment = WD_ALIGN_PARAGRAPH.LEFT
        fr = footer.add_run("Руководство пользователя ПО HVP")
        set_run_font(fr, size=10, color=(80, 80, 80))
        footer.add_run("          ")
        add_page_number(footer)

        settings = self.doc.settings.element
        upd = OxmlElement("w:updateFields")
        upd.set(qn("w:val"), "true")
        settings.append(upd)

    def title(self, text, size=20, after=6):
        p = self.doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_after = Pt(after)
        p.paragraph_format.space_before = Pt(0)
        r = p.add_run(text)
        set_run_font(r, size=size, bold=True, color=(20, 40, 70))
        return p

    def h1(self, text):
        self.doc.add_page_break()
        p = self.doc.add_paragraph()
        p.style = self.doc.styles["Heading 1"]
        p.paragraph_format.space_before = Pt(0)
        p.paragraph_format.space_after = Pt(10)
        r = p.add_run(text)
        set_run_font(r, size=16, bold=True, color=(20, 40, 70))
        return p

    def h2(self, text):
        p = self.doc.add_paragraph()
        p.style = self.doc.styles["Heading 2"]
        p.paragraph_format.space_before = Pt(12)
        p.paragraph_format.space_after = Pt(6)
        r = p.add_run(text)
        set_run_font(r, size=14, bold=True, color=(30, 55, 90))
        return p

    def p(self, text):
        p = self.doc.add_paragraph()
        r = p.add_run(text)
        set_run_font(r, size=12)
        style_body(p)
        return p

    def bullets(self, items):
        for item in items:
            p = self.doc.add_paragraph()
            p.paragraph_format.left_indent = Cm(0.75)
            p.paragraph_format.space_after = Pt(3)
            p.paragraph_format.space_before = Pt(0)
            r = p.add_run("–  " + item)
            set_run_font(r, size=12)
            p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY

    def steps(self, items):
        for i, item in enumerate(items, 1):
            p = self.doc.add_paragraph()
            p.paragraph_format.left_indent = Cm(0.75)
            p.paragraph_format.space_after = Pt(4)
            r = p.add_run(f"{i}.  {item}")
            set_run_font(r, size=12)
            p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY

    def note(self, text):
        p = self.doc.add_paragraph()
        r = p.add_run(text)
        set_run_font(r, size=12, italic=True, color=(60, 70, 80))
        style_body(p, after=10)

    def figure(self, filename, caption):
        global fig_no
        fig_no += 1
        path = IMG / filename
        p = self.doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_before = Pt(8)
        p.paragraph_format.space_after = Pt(2)
        run = p.add_run()
        run.add_picture(str(path), width=Cm(16.2))
        cap = self.doc.add_paragraph()
        cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
        cap.paragraph_format.space_after = Pt(10)
        cr = cap.add_run(f"Рисунок {fig_no}. {caption}")
        set_run_font(cr, size=11, italic=True)
        return fig_no

    def table(self, headers, rows, col_widths):
        table = self.doc.add_table(rows=1 + len(rows), cols=len(headers))
        table.style = "Table Grid"
        for i, h in enumerate(headers):
            cell = table.rows[0].cells[i]
            cell.text = ""
            p = cell.paragraphs[0]
            r = p.add_run(h)
            set_run_font(r, size=11, bold=True, color=(255, 255, 255))
            shade_cell(cell, "1E3A5F")
        for ri, row in enumerate(rows):
            for ci, val in enumerate(row):
                cell = table.rows[ri + 1].cells[ci]
                cell.text = ""
                p = cell.paragraphs[0]
                r = p.add_run(val)
                set_run_font(r, size=11)
                if ri % 2 == 1:
                    shade_cell(cell, "F4F7FB")
        for row in table.rows:
            for i, w in enumerate(col_widths):
                row.cells[i].width = Cm(w)
        self.doc.add_paragraph().paragraph_format.space_after = Pt(4)


