import * as XLSX from "xlsx";

type SheetRow = Record<string, string | number>;

const LABOR_IMPORT_DEPARTMENTS = ["ME", "AV", "INT", "NDT", "SHOP", "CabRep"] as const;
const LABOR_IMPORT_BLOCKS = [
  { prefix: "laborBudget", title: "Трудоемкость (Бюджет)" },
  { prefix: "laborAddBudget", title: "Трудоемкость на ADD (Бюджет)" },
  { prefix: "laborNrcBudget", title: "Трудоемкость на NRC (Бюджет)" },
  { prefix: "laborMps", title: "Плановая трудоемкость WP согласно MPS" },
  { prefix: "laborActual", title: "Фактическая трудоемкость WP (завершенное)" },
  { prefix: "laborAddPlan", title: "Трудоемкость на ADD (План)" },
  { prefix: "laborNrcPlan", title: "Трудоемкость на NRC (План)" },
  { prefix: "laborAddActual", title: "Фактические данные ADD (Факт)" },
  { prefix: "laborNrcActual", title: "Фактические данные NRC (Факт)" }
] as const;

function laborImportExampleValues(prefix: string): Record<string, number | ""> {
  const out: Record<string, number | ""> = {};
  for (const dep of LABOR_IMPORT_DEPARTMENTS) {
    // В примере заполняем только MPS — бюджет/факт оставляем пустыми.
    out[`${prefix}_${dep}`] = prefix === "laborMps" ? (dep === "ME" ? 120 : dep === "AV" ? 40 : 0) : "";
  }
  return out;
}

/** Лист с данными из шаблона: «Данные», иначе первый лист кроме «Инструкция». */
export function readImportDataSheet(buffer: ArrayBuffer) {
  const workbook = XLSX.read(buffer, { type: "array", cellDates: false });
  const sheetName =
    workbook.SheetNames.find((name) => name.trim().toLocaleLowerCase("ru-RU") === "данные") ??
    workbook.SheetNames.find((name) => name.trim().toLocaleLowerCase("ru-RU") !== "инструкция") ??
    workbook.SheetNames[0];
  const sheet = sheetName ? workbook.Sheets[sheetName] : undefined;
  if (!sheet) throw new Error("В файле нет листа с данными.");
  return sheet;
}

/** CSV с разделителем «;» из листа «Данные». Инструкция в файл не попадает. */
export function readImportTableCsv(buffer: ArrayBuffer) {
  return XLSX.utils.sheet_to_csv(readImportDataSheet(buffer), { FS: ";", RS: "\n", blankrows: false });
}

function downloadWorkbook(filename: string, sheets: Array<{ name: string; rows: SheetRow[] }>) {
  const wb = XLSX.utils.book_new();
  for (const sheet of sheets) {
    const ws = XLSX.utils.json_to_sheet(sheet.rows);
    const keys = Object.keys(sheet.rows[0] ?? {});
    if (keys.includes("Описание")) {
      ws["!cols"] = keys.map((key) => ({ wch: key === "Описание" ? 96 : key === "Колонка" ? 28 : 16 }));
    }
    XLSX.utils.book_append_sheet(wb, ws, sheet.name.slice(0, 31));
  }
  XLSX.writeFile(wb, filename);
}

